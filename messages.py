# ── Сводка ───────────────────────────────────────────────────────

def build_summary(goal: str, achievements: list, days: int) -> str:
    lines = [
        f"📊 *Твои достижения за {days} дн.*\n",
        f"Твоя цель: _{goal}_\n",
        "Посмотри, сколько всего ты сделал(а):\n",
    ]
    for i, ach in enumerate(achievements, 1):
        lines.append(f"{i}\\. {ach['text']}")

    lines.append(f"\n✨ Это *{len(achievements)} шагов*\\! Каждый из них — твой\\.")
    lines.append("\nОцени от 1 до 10, насколько эти действия помогли тебе приблизиться к цели?")
    lines.append("_Просто напиши цифру от 1 до 10_")
    return "\n".join(lines)

