# ── Сводка ───────────────────────────────────────────────────────

def build_summary(goal: str, achievements: list, days: int) -> str:
    lines = [
        f"📊 *Твои моменты за {days} дн\\.*\n",
        f"Твой запрос: _{goal}_\n",
        "Посмотри, сколько всего было:\n",
    ]
    for i, ach in enumerate(achievements, 1):
        text = ach['text'].replace("\\", "\\\\").replace("*", "\\*").replace("_", "\\_").replace("[", "\\[").replace("`", "\\`").replace(".", "\\.").replace("!", "\\!").replace("-", "\\-").replace("(", "\\(").replace(")", "\\)").replace("+", "\\+").replace("=", "\\=").replace("|", "\\|").replace("{", "\\{").replace("}", "\\}").replace("#", "\\#").replace(">", "\\>")
        lines.append(f"{i}\\. {text}")

    lines.append(f"\n✨ Это *{len(achievements)} момент{'а' if 2 <= len(achievements) % 10 <= 4 and len(achievements) % 100 not in range(11,15) else 'ов' if len(achievements) % 10 in (0, 5,6,7,8,9) or len(achievements) % 100 in range(11,15) else ''}*\\. Каждый из них — твой\\.")
    lines.append("\nОцени от 1 до 10, насколько всё это помогло тебе приблизиться к твоей точке Б?")
    lines.append("_Просто напиши цифру от 1 до 10_")
    return "\n".join(lines)

